const BY_NAME = Object.fromEntries(LUCIDE_ICON_CATALOG.map((i) => [i.name, i.Icon]))

function toPascalIconName(raw) {
  const s = String(raw || '').trim()
  if (!s) return ''
  if (BY_NAME[s]) return s
  // handshake / message-circle / message_circle → MessageCircle
  return s
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join('')
}

export function resolveLucideIcon(name, fallback = Home) {
  if (!name) return fallback
  if (BY_NAME[name]) return BY_NAME[name]
  const pascal = toPascalIconName(name)
  return BY_NAME[pascal] || fallback
}

export function searchLucideIcons(query) {
  const q = String(query || '').trim().toLowerCase()
  if (!q) return LUCIDE_ICON_CATALOG
  return LUCIDE_ICON_CATALOG.filter(
    (i) =>
      i.name.toLowerCase().includes(q) ||
      i.label.toLowerCase().includes(q)
  )
}

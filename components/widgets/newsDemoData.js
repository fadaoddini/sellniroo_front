export function getDemoNews(count = 20) {
  const n = Math.max(1, Math.min(20, count))
  return Array.from({ length: n }, (_, i) => {
    const id = `demo-news-${i + 1}`
    return {
      id,
      slug: id,
      title: DEMO_TITLES[i % DEMO_TITLES.length],
      lid: DEMO_LEADS[i % DEMO_LEADS.length],
      excerpt: DEMO_LEADS[i % DEMO_LEADS.length],
      writer_name: ['سارا محمدی', 'علی رضایی', 'مریم احمدی', 'حسین کریمی'][i % 4],
      like_count: 12 + ((i * 7) % 90),
      view_count: 120 + ((i * 37) % 2400),
      likes: 12 + ((i * 7) % 90),
      views: 120 + ((i * 37) % 2400),
      featured_image: `https://picsum.photos/seed/sellniroo${i + 1}/800/600`,
      featured_image_url: `https://picsum.photos/seed/sellniroo${i + 1}/800/600`,
      is_demo: true,
    }
  })
}

/** اگر لیست کوتاه/خالی بود تا count (حداقل ۲۰ وقتی کاملاً خالی) با دمو پر می‌شود */
export function fillNewsWithDemo(list, count) {
  const base = Array.isArray(list) ? [...list] : []
  const want =
    base.length === 0
      ? Math.max(20, Math.min(20, count || 20))
      : Math.max(1, Math.min(20, count || 5))
  if (base.length >= want) return base.slice(0, want)
  const demos = getDemoNews(want)
  return [...base, ...demos.slice(0, want - base.length)]
}

/** مراحل تور را طوری فیلتر کن که هدف‌های موجود در DOM بمانند */
export function filterTourStepsToDom(steps) {
  if (typeof document === 'undefined') return steps
  return (steps || []).filter((step) => {
    if (!step?.target) return true
    const selectors = String(step.target)
      .split(',')
      .map((s) => s.trim())
      .filter(Boolean)
    return selectors.some((sel) => document.querySelector(sel))
  })
}

export function resolveDashboardTour(sectionId) {
  if (!sectionId || sectionId === 'full') return DASHBOARD_FULL_TOUR
  return DASHBOARD_SECTION_TOURS[sectionId] || DASHBOARD_FULL_TOUR
}

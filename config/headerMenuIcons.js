export const HEADER_MENU_ICON_IDS = HEADER_MENU_ICON_CATALOG.map((x) => x.id)

export const HEADER_MENU_ICON_MAP = Object.fromEntries(
  HEADER_MENU_ICON_CATALOG.map((x) => [x.id, x.Icon])
)

export function resolveHeaderMenuIcon(name) {
  if (!name) return Home
  return HEADER_MENU_ICON_MAP[name] || Home
}

/** پیشنهاد آیکن Lucide از روی href و عنوان */
export function suggestHeaderMenuIcon({ href = '', label_fa = '', label_en = '' } = {}) {
  const path = String(href || '')
    .trim()
    .toLowerCase()
    .split('?')[0]
    .split('#')[0]
  const text = `${label_fa} ${label_en} ${path}`.toLowerCase()

  const rules = [
    [/^(?:\/)?$|^\/$|خانه|\bhome\b/, 'Home'],
    [/آگهی|استخدام|job|career|brief/, 'Briefcase'],
    [/خبر|news|مقاله|blog/, 'Newspaper'],
    [/سوال|faq|help|راهنما/, 'HelpCircle'],
    [/مدرس|آموزش|school|course|learn|edu/, 'GraduationCap'],
    [/نرم.?افزار|\/apps|softapp|application/, 'AppWindow'],
    [/تعمیر|repair|service.?tech|wrench/, 'Wrench'],
    [/درباره|about|info/, 'Info'],
    [/ثبت.?آگهی|post-?job|add.?job|جدید/, 'PlusCircle'],
    [/فروشگاه|\/shop|store|product|محصول/, 'ShoppingBag'],
    [/سبد|\/cart|checkout|خرید/, 'ShoppingCart'],
    [/تماس|contact|phone|call/, 'Phone'],
    [/ایمیل|mail|email/, 'Mail'],
    [/پروفایل|profile|account|کاربر/, 'User'],
    [/نوبت|booking|رزرو|appointment|calendar/, 'Calendar'],
    [/آزمون|quiz|form|clipboard/, 'ClipboardList'],
    [/فروش|sale|marketing|رشد/, 'TrendingUp'],
    [/پرداخت|payment|card|wallet/, 'CreditCard'],
    [/گالری|gallery|image|photo/, 'Image'],
    [/ویدیو|video|film/, 'Video'],
    [/داشبورد|dashboard|admin/, 'LayoutDashboard'],
    [/ورود|login|signin/, 'LogIn'],
    [/خروج|logout/, 'LogOut'],
    [/تنظیم|setting/, 'Settings'],
    [/امن|shield|security/, 'Shield'],
    [/تیم|users|team|کارمند/, 'Users'],
    [/شرکت|company|building|سازمان/, 'Building2'],
    [/جستجو|search/, 'Search'],
    [/ابری|cloud|server/, 'Cloud'],
    [/کشاورز|agri|leaf|گیاه/, 'Leaf'],
    [/طراح|design|palette|brand/, 'Palette'],
    [/کد|dev|code/, 'Code2'],
    [/موبایل|mobile|phone.?app/, 'Smartphone'],
  ]

  for (const [re, icon] of rules) {
    if (re.test(text) || re.test(path)) return icon
  }
  return 'Link2'
}

export function normalizeHeaderMenuIconId(raw) {
  const id = String(raw || '').trim()
  if (HEADER_MENU_ICON_MAP[id]) return id
  return 'Home'
}

function pxNum(v, fallback, max = 80) {
  const n = Number(v)
  if (!Number.isFinite(n)) return fallback
  return Math.max(0, Math.min(max, Math.round(n * 10) / 10))
}

function hexToRgba(hex, alpha = 0.12) {
  const m = /^#([0-9a-f]{6})$/i.exec(String(hex || '').trim())
  if (!m) return null
  const n = parseInt(m[1], 16)
  const r = (n >> 16) & 255
  const g = (n >> 8) & 255
  const b = n & 255
  return `rgba(${r}, ${g}, ${b}, ${alpha})`
}

export function applySadraPixelTheme(themeKey, current = {}) {
  const theme = SADRA_PIXEL_THEMES[themeKey]
  if (!theme) return { ...current, theme: 'custom' }
  return {
    ...current,
    theme: themeKey,
    color: theme.color,
    color_glow: theme.color_glow,
    color_dim: theme.color_dim,
    board_bg: theme.board_bg,
    board_border: theme.board_border,
  }
}

export function normalizeSadraPixelSettings(raw = {}) {
  const d = DEFAULT_SADRA_PIXEL_SETTINGS
  let s = { ...d, ...(raw || {}) }
  const rawTitle = String(s.title ?? '').trim()
  s.title = rawTitle || d.title

  let themeKey = String(s.theme || d.theme).trim() || 'red'
  if (themeKey !== 'custom' && SADRA_PIXEL_THEMES[themeKey]) {
    // همیشه رنگ‌های تم انتخاب‌شده را هم‌تراز کن
    s = applySadraPixelTheme(themeKey, s)
  } else if (themeKey === 'custom') {
    s.theme = 'custom'
  } else {
    s = applySadraPixelTheme('red', s)
  }

  s.pixel_size = Math.max(4, Math.min(16, pxNum(s.pixel_size, d.pixel_size, 16)))
  s.pixel_gap = Math.max(0, Math.min(5, pxNum(s.pixel_gap, d.pixel_gap, 5)))
  s.letter_gap = Math.max(2, Math.min(28, pxNum(s.letter_gap, d.letter_gap, 28)))
  s.color = String(s.color || d.color).trim() || d.color
  s.color_glow = String(s.color_glow || d.color_glow).trim() || d.color_glow
  s.color_dim =
    String(s.color_dim || '').trim() ||
    hexToRgba(s.color, 0.22) ||
    d.color_dim
  s.board_bg = String(s.board_bg || d.board_bg).trim() || d.board_bg
  s.board_border =
    String(s.board_border || d.board_border).trim() || d.board_border
  s.animate =
    raw && Object.prototype.hasOwnProperty.call(raw, 'animate')
      ? !!raw.animate
      : d.animate
  s.scroll_direction =
    s.scroll_direction === 'to_right' ? 'to_right' : 'to_left'
  s.text_direction = ['ltr', 'rtl', 'auto'].includes(s.text_direction)
    ? s.text_direction
    : 'auto'
  s.scroll_seconds = Math.max(
    4,
    Math.min(40, pxNum(s.scroll_seconds, d.scroll_seconds, 40))
  )
  s.padding_top = pxNum(s.padding_top, d.padding_top, 80)
  s.padding_bottom = pxNum(s.padding_bottom, d.padding_bottom, 80)
  s.show_on_mobile =
    raw && Object.prototype.hasOwnProperty.call(raw, 'show_on_mobile')
      ? !!raw.show_on_mobile
      : d.show_on_mobile
  s.show_on_desktop =
    raw && Object.prototype.hasOwnProperty.call(raw, 'show_on_desktop')
      ? !!raw.show_on_desktop
      : d.show_on_desktop
  return s
}

export function resolveSadraTextDirection(settings) {
  const s = normalizeSadraPixelSettings(settings)
  if (s.text_direction === 'ltr' || s.text_direction === 'rtl') {
    return s.text_direction
  }
  return /[\u0600-\u06FF]/.test(s.title || '') ? 'rtl' : 'ltr'
}

export function sadraPixelCssVars(settings) {
  const s = normalizeSadraPixelSettings(settings)
  // اندازه پیکسل تنظیمات → اندازه فونت LED (۴→۲۲px … ۱۶→52px)
  const fontPx = Math.round(10 + s.pixel_size * 3.2)
  return {
    '--spx-size': `${s.pixel_size}px`,
    '--spx-font': `${fontPx}px`,
    '--spx-gap': `${s.pixel_gap}px`,
    '--spx-letter-gap': `${s.letter_gap}px`,
    '--spx-color': s.color,
    '--spx-glow': s.color_glow,
    '--spx-dim': s.color_dim,
    '--spx-board': s.board_bg,
    '--spx-board-border': s.board_border,
    '--spx-pad-t': `${s.padding_top}px`,
    '--spx-pad-b': `${s.padding_bottom}px`,
    '--spx-scroll': `${s.scroll_seconds}s`,
  }
}


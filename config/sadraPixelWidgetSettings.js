export function getSadraPixelGlyph(char) {
  if (!char) return null
  if (/[a-z]/i.test(char)) {
    return SADRA_PIXEL_GLYPHS[char.toUpperCase()] || null
  }
  return SADRA_PIXEL_GLYPHS[char] || null
}
